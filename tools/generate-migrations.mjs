// Generates shared/db/migrations.generated.ts from shared/db/migrations/*.sql.
//
// Why generate instead of importing the .sql directly: Node cannot import a
// .sql file, and the Angular builder's `.sql` loader disables Node builtin
// resolution in the unit-test builder (which broke `node:sqlite` in specs).
// A generated TypeScript module works everywhere and keeps 001_initial.sql the
// single source of truth; verify-migration.mjs fails if this file drifts.
//
// Run: node tools/generate-migrations.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { migrationsDir, readMigrationSources, sourceDigest } from './lib/migration-source.mjs';

const sources = readMigrationSources();
const digest = sourceDigest(sources);
const outFile = join(migrationsDir, '..', 'migrations.generated.ts');

const contents = [
  '// AUTO-GENERATED by tools/generate-migrations.mjs. Do not edit by hand.',
  '// Regenerate with: node tools/generate-migrations.mjs',
  `// source-hash: ${digest}`,
  '',
  '/**',
  ' * Ordered migration SQL, index 0 = version 1. The runtime runner',
  ' * (shared/db/migrate.ts) applies migrations[user_version..], so the order',
  ' * here is load-bearing.',
  ' */',
  'export const MIGRATIONS: readonly string[] = [',
  ...sources.map(({ sql }) => `  ${JSON.stringify(sql)},`),
  '];',
  '',
].join('\n');

writeFileSync(outFile, contents, 'utf8');
console.log(`wrote ${outFile} (${sources.length} migration(s), hash ${digest.slice(0, 12)}...)`);
